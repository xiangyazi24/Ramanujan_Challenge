#!/usr/bin/env python3
"""Verify the explicit 6-isogeny behind the Franel deck involution.

The Franel elliptic pencil is

    E_u: y^2 + (1-2u)xy + u^2 y = x^3.

The other point above t=u(1-8u)/(1+u) is

    v=iota(u)=(1-8u)/(8(1+u)).

The cyclic subgroup generated by (u,-u) has order six.  Velu's quotient is
the curve C_u below.  It is not isomorphic to E_v over Q(u): it is the
constant quadratic twist by -3.  Over Q(sqrt(-3))(u), the final coordinate
change below identifies C_u and E_v.  Thus Sym^2, but not R^1 itself over Q,
descends through the involution.

The exact rational maps and the coordinate change are checked symbolically.
They are then evaluated on every non-kernel affine point for five split good
primes.  This script uses only sympy and the Python standard library.
"""

from __future__ import annotations

import sympy as sp


def exact_formulae() -> tuple[sp.Expr, ...]:
    u, x, y, w = sp.symbols("u x y w")

    a1 = 1 - 2 * u
    a3 = u**2
    source = y**2 + a1 * x * y + a3 * y - x**3

    def double(point: tuple[sp.Expr, sp.Expr]) -> tuple[sp.Expr, sp.Expr]:
        x1, y1 = point
        denominator = 2 * y1 + a1 * x1 + a3
        slope = sp.factor((3 * x1**2 - a1 * y1) / denominator)
        intercept = sp.factor((-x1**3 - a3 * y1) / denominator)
        x3 = sp.factor(slope**2 + a1 * slope - 2 * x1)
        y3 = sp.factor(-(slope + a1) * x3 - intercept - a3)
        return x3, y3

    def add_distinct(
        first: tuple[sp.Expr, sp.Expr], second: tuple[sp.Expr, sp.Expr]
    ) -> tuple[sp.Expr, sp.Expr]:
        x1, y1 = first
        x2, y2 = second
        slope = sp.factor((y2 - y1) / (x2 - x1))
        intercept = sp.factor((y1 * x2 - y2 * x1) / (x2 - x1))
        x3 = sp.factor(slope**2 + a1 * slope - x1 - x2)
        y3 = sp.factor(-(slope + a1) * x3 - intercept - a3)
        return x3, y3

    generator = (u, -u)
    twice = double(generator)
    thrice = add_distinct(generator, twice)
    assert twice == (0, -u**2)
    assert thrice == (-u**2, -u**3)
    # thrice is fixed by Weierstrass negation, while generator is not.
    assert sp.factor(-thrice[1] - a1 * thrice[0] - a3 - thrice[1]) == 0
    assert sp.factor(-generator[1] - a1 * generator[0] - a3 - generator[1]) != 0
    # The degree-six Velu quotient.  Sage's normalization retains a1,a3.
    a4c = -5 * u**4 - 5 * u**3 - 20 * u**2 - 5 * u
    a6c = 3 * u**6 + 7 * u**5 - 41 * u**4 - 24 * u**3 - 14 * u**2 - u

    dx = x**2 * (x - u) ** 2 * (x + u**2)
    nx = (
        x**6
        + (u**2 - 2 * u) * x**5
        + (u**4 - u**3 + 5 * u**2 + u) * x**4
        + (-2 * u**5 + 7 * u**4 - 2 * u**3) * x**3
        + (5 * u**6 - 6 * u**5 + u**4) * x**2
        + (-4 * u**7 + 2 * u**6) * x
        + u**8
    )

    dy = x**3 * (x - u) ** 3 * (x + u**2) ** 2
    ny = (
        x**8 * y
        + (2 * u**2 - 3 * u) * x**7 * y
        + (2 * u**5 + u**4 + 7 * u**3 - 2 * u**2 - u) * x**7
        + (-7 * u**3 - u**2 - u) * x**6 * y
        + (u**7 - 6 * u**6 + 24 * u**5 - 18 * u**4 + 2 * u**3) * x**6
        + (-7 * u**4 - u**3 - u**2) * x**5 * y
        + (-3 * u**8 + 38 * u**7 - 54 * u**6 + 22 * u**5 - 4 * u**4) * x**5
        + (-20 * u**6 + 10 * u**5 - 5 * u**4) * x**4 * y
        + (15 * u**9 - 67 * u**8 + 55 * u**7 - 17 * u**6 + u**5) * x**4
        + (-8 * u**8 + 26 * u**7 - 14 * u**6 + u**5) * x**3 * y
        + (-25 * u**10 + 56 * u**9 - 30 * u**8 + 4 * u**7) * x**3
        + (12 * u**9 - 19 * u**8 + 4 * u**7) * x**2 * y
        + (19 * u**11 - 24 * u**10 + 6 * u**9) * x**2
        + (-8 * u**10 + 5 * u**9) * x * y
        + (-7 * u**12 + 4 * u**11) * x
        + 2 * u**11 * y
        + u**13
    )

    # Verify the rational map exactly.  Since dy^2=dx^3*(x+u^2), the
    # following is the target equation after multiplication by dy^2.  This
    # sparse clearing is much faster than asking a CAS to combine fractions.
    cleared_target = sp.expand(
        ny**2
        + a1 * nx * ny * (dy / dx)
        + a3 * ny * dy
        - nx**3 * (x + u**2)
        - a4c * nx * (dy**2 / dx)
        - a6c * dy**2
    )
    reduced = sp.rem(sp.Poly(cleared_target, y), sp.Poly(source, y)).as_expr()
    assert sp.factor(reduced) == 0
    assert sp.degree(nx, x) == 6 and sp.degree(dx, x) == 5
    assert sp.gcd(sp.Poly(nx, x), sp.Poly(dx, x)) == 1
    # Deck involution and equality of its quotient coordinate.
    v = (1 - 8 * u) / (8 * (1 + u))
    phi = lambda z: z * (1 - 8 * z) / (1 + z)
    assert sp.factor(phi(v) - phi(u)) == 0
    assert sp.factor((1 - 8 * v) / (8 * (1 + v)) - u) == 0

    # Isomorphism C_u -> E_v after adjoining w^2=-3.  In the standard
    # Weierstrass change, source coordinates satisfy
    #   X_C=q^2 X_v+r,
    #   Y_C=q^3 Y_v+q^2 s X_v+t.
    q = 4 * (u + 1) * w / 3
    r = -(13 * u**2 + 5 * u + 1) / 3
    s = (4 * u * w + 2 * u + w - 1) / 2
    tt = -(64 * u**3 * w + 78 * u**3 + 48 * u**2 * w - 15 * u * w - 9 * u + w - 3) / 18

    def reduce_w(expression: sp.Expr) -> sp.Expr:
        numerator, denominator = sp.cancel(expression).as_numer_denom()
        numerator = sp.rem(sp.Poly(numerator, w), sp.Poly(w**2 + 3, w)).as_expr()
        denominator = sp.rem(sp.Poly(denominator, w), sp.Poly(w**2 + 3, w)).as_expr()
        return sp.factor(numerator / denominator)

    a1v = 1 - 2 * v
    a3v = v**2

    # Check the six coefficient identities for the standard change
    # x_C=q^2*x_v+r, y_C=q^3*y_v+q^2*s*x_v+tt.  This is much faster and
    # algebraically stronger than testing the coordinate change at samples.
    changes = [
        q * a1v - (a1 + 2 * s),
        -(0 - s * a1 + 3 * r - s**2),
        q**3 * a3v - (a3 + r * a1 + 2 * tt),
        -(a4c - s * a3 - (tt + r * s) * a1 + 3 * r**2 - 2 * s * tt),
        -(a6c + r * a4c + r**3 - tt * a3 - r * tt * a1 - tt**2),
        q**2 + 16 * (u + 1) ** 2 / 3,
    ]
    assert all(reduce_w(expression) == 0 for expression in changes)

    # The normalized symmetric-square correspondence used in Q6394 divides
    # by the degree six.  Its Hodge-line scalar is rational and satisfies the
    # deck cocycle, although the rank-two isomorphism itself needs w^2=-3.
    hodge_scalar = sp.Rational(8, 9) * (1 + u) ** 2
    assert reduce_w(-q**2 / 6 - hodge_scalar) == 0
    partner_scalar = sp.Rational(8, 9) * (1 + v) ** 2
    assert sp.factor(hodge_scalar * partner_scalar - 1) == 0

    print("VERIFIED exact Franel model and deck involution phi(iota(u))=phi(u)")
    print("VERIFIED Q=(u,-u) has exact order 6 and kernel x-coordinates 0,u,-u^2")
    print("VERIFIED exact formulas for the cyclic 6-isogeny E_u -> C_u")
    print("VERIFIED C_u becomes E_iota(u) over Q(sqrt(-3))(u); twist class is -3")
    print("VERIFIED normalized Sym^2 scalar g(u)=8(1+u)^2/9 and g(u)g(iota(u))=1")
    return u, x, y, w, v, nx, dx, ny, dy, a4c, a6c, q, r, s, tt


def inv(value: int, prime: int) -> int:
    return pow(value % prime, -1, prime)


def legendre(value: int, prime: int) -> int:
    value %= prime
    if value == 0:
        return 0
    return 1 if pow(value, (prime - 1) // 2, prime) == 1 else -1


def elliptic_trace(parameter: int, prime: int) -> int:
    """Count E_parameter(F_p) on the displayed Weierstrass model."""
    a1 = (1 - 2 * parameter) % prime
    a3 = parameter * parameter % prime
    points = 1
    for x_value in range(prime):
        linear_y = (a1 * x_value + a3) % prime
        discriminant = (linear_y * linear_y + 4 * x_value**3) % prime
        points += 1 + legendre(discriminant, prime)
    return prime + 1 - points


def eval_expr(expression: sp.Expr, values: dict[sp.Symbol, int], prime: int) -> int:
    numerator, denominator = sp.cancel(expression).as_numer_denom()
    n = int(numerator.subs(values)) % prime
    d = int(denominator.subs(values)) % prime
    return n * inv(d, prime) % prime


def verify_five_primes(data: tuple[sp.Expr, ...]) -> None:
    u, x, y, w, v_expr, nx, dx, ny, dy, a4c, a6c, q, r, s, tt = data
    primes = [7, 13, 19, 31, 37]  # -3 is a square for each prime.
    checked = 0
    # Avoid SymPy substitution in the inner finite-field point loop.
    nx_fast = sp.lambdify((u, x), nx, "math")
    dx_fast = sp.lambdify((u, x), dx, "math")
    ny_fast = sp.lambdify((u, x, y), ny, "math")
    dy_fast = sp.lambdify((u, x), dy, "math")

    for prime in primes:
        w_value = next(z for z in range(prime) if (z * z + 3) % prime == 0)
        inverse_eight = inv(8, prime)
        singular = {0, prime - 1, inverse_eight}
        prime_checked = 0

        for u_value in range(prime):
            if u_value in singular:
                continue
            v_value = (1 - 8 * u_value) * inv(8 * (1 + u_value), prime) % prime
            a1 = (1 - 2 * u_value) % prime
            a3 = u_value**2 % prime
            a1v = (1 - 2 * v_value) % prime
            a3v = v_value**2 % prime
            a4_value = (-5*u_value**4-5*u_value**3-20*u_value**2-5*u_value) % prime
            a6_value = (3*u_value**6+7*u_value**5-41*u_value**4-24*u_value**3-14*u_value**2-u_value) % prime
            qv = 4 * (u_value + 1) * w_value * inv(3, prime) % prime
            rv = -(13 * u_value**2 + 5 * u_value + 1) * inv(3, prime) % prime
            sv = (4*u_value*w_value+2*u_value+w_value-1) * inv(2, prime) % prime
            tv = -(64*u_value**3*w_value+78*u_value**3+48*u_value**2*w_value-15*u_value*w_value-9*u_value+w_value-3) * inv(18, prime) % prime

            for x_value in range(prime):
                # These are precisely the affine kernel x-coordinates.
                if x_value in {0, u_value, (-u_value**2) % prime}:
                    continue
                for y_value in range(prime):
                    if (y_value**2 + a1 * x_value * y_value + a3 * y_value - x_value**3) % prime:
                        continue
                    xc = nx_fast(u_value, x_value) % prime * inv(dx_fast(u_value, x_value), prime) % prime
                    yc = ny_fast(u_value, x_value, y_value) % prime * inv(dy_fast(u_value, x_value), prime) % prime
                    assert (
                        yc**2 + a1 * xc * yc + a3 * yc - xc**3 - a4_value * xc - a6_value
                    ) % prime == 0

                    xv = (xc - rv) * inv(qv**2, prime) % prime
                    yv = (yc - sv * (xc - rv) - tv) * inv(qv**3, prime) % prime
                    assert (yv**2 + a1v * xv * yv + a3v * yv - xv**3) % prime == 0
                    checked += 1
                    prime_checked += 1

        assert prime_checked > 0
        print(f"VERIFIED p={prime}: rational map lands on E_iota(u) at {prime_checked} affine points")

    print(f"VERIFIED explicit isogeny at five primes ({checked} point evaluations total)")


def verify_trace_twist() -> None:
    """Check the load-bearing -3 twist, including nonsplit primes."""
    checked = 0
    nonsplit = 0
    for prime in (5, 7, 11, 13, 17):
        twist_sign = legendre(-3, prime)
        nonsplit += twist_sign == -1
        singular = {0, prime - 1, inv(8, prime)}
        for parameter in range(prime):
            if parameter in singular:
                continue
            partner = (
                (1 - 8 * parameter) * inv(8 * (1 + parameter), prime)
            ) % prime
            assert partner not in singular
            assert elliptic_trace(partner, prime) == twist_sign * elliptic_trace(
                parameter, prime
            )
            checked += 1
    assert nonsplit > 0
    print(
        "VERIFIED a_p(E_iota(u))=(-3|p)*a_p(E_u) at "
        f"p=5,7,11,13,17 ({checked} smooth fibers; split and nonsplit twists)"
    )


if __name__ == "__main__":
    verify_five_primes(exact_formulae())
    verify_trace_twist()
