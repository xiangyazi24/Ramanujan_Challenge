def balanced_blocks(count, seed, maximum_index):
    """Random cores whose left and right first-cell margins differ by <= 1."""

    generator = random.Random(seed)
    blocks = []
    while len(blocks) < count:
        index = generator.randrange(_sage_const_80 , maximum_index + _sage_const_1 )
        N = generator.randrange(max(_sage_const_8 , index // _sage_const_12 ), max(_sage_const_9 , index // _sage_const_4 ))
        midpoint = (index - _sage_const_1 ) // _sage_const_2 
        # Solve D-midpoint = index+1-D-N up to the nearest integer.
        D = (index + _sage_const_1  + midpoint - N) // _sage_const_2 
        if abs((D - midpoint) - (index + _sage_const_1  - D - N)) > _sage_const_1 :
            continue
        if margin_data(index, D, N)[_sage_const_0 ] < _sage_const_2 :
            continue
        if not any(
            index - prime + _sage_const_9  <= prime - _sage_const_5 
            for prime in prime_range(D + _sage_const_1 , D + N + _sage_const_1 )
        ):
            continue
        blocks.append((index, D, N))
    return tuple(blocks)


