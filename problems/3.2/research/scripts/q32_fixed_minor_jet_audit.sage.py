def margin_data(index, D, N):
    moment = index - _sage_const_1 
    maximum_margin = min(
        D - moment // _sage_const_2 ,
        moment - D - N + _sage_const_2 ,
    )
    assert maximum_margin >= _sage_const_2 
    return maximum_margin, (maximum_margin - _sage_const_1 , maximum_margin)


def newton_mod(values, lower_node, length, modulus):
    return ZZ(
        sum(
            (-_sage_const_1 )**offset
            * binomial(lower_node + offset, offset)
            * binomial(
                lower_node + length + _sage_const_1 ,
                length - offset,
            )
            * values[lower_node + offset]
            for offset in range(length + _sage_const_1 )
        )
        % modulus
    )


def divided_newton_formula(values, lower_node, length, prime):
    """Return ``G_{d,L}(F)/p mod p`` from the first divided node digit.

    This applies when ``L<p``, ``p-1=d+j`` is in the stencil, and
    ``F_{p-1}=0 mod p``.  Put ``s=L-j``.  The off-node coefficients are
    the once-divided Newton weights:

      i<j: (-1)^(j-i-1) C(j,i) s!(j-i-1)!/(s+j-i)!,
      i=j+t: (-1)^t C(s,t) (t-1)!j!/(j+t)!.
    """

    j = prime - _sage_const_1  - lower_node
    s = length - j
    assert _sage_const_0  <= j <= length < prime
    assert values[prime - _sage_const_1 ] % prime == _sage_const_0 
    answer = (values[prime - _sage_const_1 ] // prime) % prime

    for i in range(j):
        numerator = (
            (-_sage_const_1 )**(j - i - _sage_const_1 )
            * binomial(j, i)
            * factorial(s)
            * factorial(j - i - _sage_const_1 )
        )
        denominator = factorial(s + j - i)
        answer += (
            numerator
            * inverse_mod(denominator, prime)
            * values[lower_node + i]
        )

    for t in range(_sage_const_1 , s + _sage_const_1 ):
        numerator = (
            (-_sage_const_1 )**t
            * binomial(s, t)
            * factorial(t - _sage_const_1 )
            * factorial(j)
        )
        denominator = factorial(j + t)
        answer += (
            numerator
            * inverse_mod(denominator, prime)
            * values[prime - _sage_const_1  + t]
        )

    return ZZ(answer % prime)


def rational_mod(value, prime):
    value = QQ(value)
    numerator = ZZ(value.numerator()) % prime
    denominator = ZZ(value.denominator()) % prime
    if denominator == _sage_const_0 :
        return None
    return ZZ(numerator * inverse_mod(denominator, prime) % prime)


def apery_mod(index, prime):
    return ZZ(apery(index) % prime)


def build_node_functions(index, D, N, modulus):
    maximum_margin, margins = margin_data(index, D, N)

    terminal_d = D - maximum_margin + _sage_const_1 
    terminal_length = N + maximum_margin - _sage_const_2 
    lower_node = terminal_d
    upper_node = D + terminal_length
    nodes = tuple(range(lower_node, upper_node + _sage_const_1 ))
    neighbours = tuple(range(lower_node - _sage_const_1 , upper_node + _sage_const_2 ))

    y_values = shell_batch(index - _sage_const_1 , nodes, modulus=modulus)
    maximum_ghost_shift = _sage_const_4  if "--all-ghosts" in sys.argv else _sage_const_1 
    maximum_time_index = max(index + _sage_const_6 , index + maximum_ghost_shift + _sage_const_5 )
    time_shells = {
        time_index: shell_batch(
            time_index,
            neighbours,
            modulus=modulus,
        )
        for time_index in range(index, maximum_time_index + _sage_const_1 )
    }

    def shell_pair(time_index, node):
        return (
            time_shells[time_index][node - _sage_const_1 ]
            + time_shells[time_index][node + _sage_const_1 ]
        ) % modulus

    shifted_y = {
        _sage_const_0 : y_values,
        _sage_const_1 : {node: time_shells[index][node] for node in nodes},
        _sage_const_2 : {node: time_shells[index + _sage_const_1 ][node] for node in nodes},
    }
    origin_shifts = {
        time_shift: {
            node: ZZ(
                (
                    sum(
                        ZZ(
                            integer_coefficients[operator_shift](
                                n=index + time_shift
                            )
                        )
                        * shell_pair(
                            index + time_shift + operator_shift,
                            node,
                        )
                        for operator_shift in range(
                            len(integer_coefficients)
                        )
                    )
                    - ZZ(multiplier(n=index + time_shift))
                    * shifted_y[time_shift][node]
                )
                % modulus
            )
            for node in nodes
        }
        for time_shift in range(_sage_const_3 )
    }
    ghost_shifts = {
        time_shift: {
            node: ZZ(
                sum(
                    ZZ(
                        ghost_coefficients[operator_shift](
                            n=index + time_shift
                        )
                    )
                    * shell_pair(
                        index + time_shift + operator_shift,
                        node,
                    )
                    for operator_shift in range(
                        len(ghost_coefficients)
                    )
                )
                % modulus
            )
            for node in nodes
        }
        for time_shift in range(maximum_ghost_shift + _sage_const_1 )
    }
    apery_defect = {
        node: ZZ(
            sum(
                ZZ(apery_operator[time_shift](n=index))
                * shifted_y[time_shift][node]
                for time_shift in range(_sage_const_3 )
            )
            % modulus
        )
        for node in nodes
    }
    return (
        margins,
        nodes,
        origin_shifts[_sage_const_0 ],
        ghost_shifts[_sage_const_1 ],
        {
            "origin_shifts": origin_shifts,
            "ghost_zero": ghost_shifts[_sage_const_0 ],
            "ghost_shifts": ghost_shifts,
            "apery_defect": apery_defect,
        },
    )


def audit_candidate(index, D, N, prime, node_functions=None):
    assert D < prime <= D + N
    assert index - prime + _sage_const_9  <= prime - _sage_const_5 
    modulus = prime**_sage_const_2 
    if node_functions is None:
        (
            margins,
            nodes,
            origin,
            ghost_one,
            auxiliary,
        ) = build_node_functions(
            index,
            D,
            N,
            modulus,
        )
    else:
        margins, nodes, origin, ghost_one, auxiliary = node_functions

    assert origin[prime - _sage_const_1 ] % prime == _sage_const_0 
    assert ghost_one[prime - _sage_const_1 ] % prime == _sage_const_0 

    residue = index - prime
    records = []
    ore_elimination_records = []
    all_ghost_records = []
    for margin in margins:
        d = D - margin + _sage_const_1 
        length = N + margin - _sage_const_2 
        assert length < prime
        columns = []
        for values in (origin, ghost_one):
            left = newton_mod(values, d, length, modulus)
            right = newton_mod(values, D, length, modulus)
            assert left % prime == _sage_const_0 
            assert right % prime == _sage_const_0 
            divided = (left // prime % prime, right // prime % prime)
            formula = (
                divided_newton_formula(values, d, length, prime),
                divided_newton_formula(values, D, length, prime),
            )
            assert divided == formula
            columns.append(divided)

        determinant = ZZ(
            (
                columns[_sage_const_0 ][_sage_const_0 ] * columns[_sage_const_1 ][_sage_const_1 ]
                - columns[_sage_const_0 ][_sage_const_1 ] * columns[_sage_const_1 ][_sage_const_0 ]
            )
            % prime
        )
        records.append((margin, determinant, tuple(columns)))

        if "--all-ghosts" in sys.argv:
            all_columns = [columns[_sage_const_0 ]]
            all_columns.extend(
                (
                    divided_newton_formula(
                        auxiliary["ghost_shifts"][shift],
                        d,
                        length,
                        prime,
                    ),
                    divided_newton_formula(
                        auxiliary["ghost_shifts"][shift],
                        D,
                        length,
                        prime,
                    ),
                )
                for shift in range(_sage_const_5 )
            )
            all_minors = tuple(
                ZZ(
                    (
                        all_columns[left][_sage_const_0 ]
                        * all_columns[right][_sage_const_1 ]
                        - all_columns[left][_sage_const_1 ]
                        * all_columns[right][_sage_const_0 ]
                    )
                    % prime
                )
                for left in range(_sage_const_6 )
                for right in range(left + _sage_const_1 , _sage_const_6 )
            )
            all_ghost_records.append(
                (
                    margin,
                    any(all_minors),
                    tuple(
                        index
                        for index, value in enumerate(all_minors)
                        if value
                    ),
                )
            )

        alpha = tuple(
            rational_mod(
                twisted_apery_operator[shift](n=residue),
                prime,
            )
            for shift in range(_sage_const_3 )
        )
        q_values = tuple(
            rational_mod(ore_quotient[shift](n=residue), prime)
            for shift in range(_sage_const_2 )
        )
        if None not in alpha + q_values:
            def divided_vector(values):
                return vector(
                    GF(prime),
                    [
                        divided_newton_formula(
                            values,
                            lower,
                            length,
                            prime,
                        )
                        for lower in (d, D)
                    ],
                )

            origin_vectors = tuple(
                divided_vector(auxiliary["origin_shifts"][shift])
                for shift in range(_sage_const_3 )
            )
            ghost_zero_vector = divided_vector(
                auxiliary["ghost_zero"]
            )
            ghost_one_vector = divided_vector(ghost_one)
            defect_vector = divided_vector(
                auxiliary["apery_defect"]
            )
            left_side = sum(
                (
                    GF(prime)(alpha[shift])
                    * origin_vectors[shift]
                    for shift in range(_sage_const_3 )
                ),
                vector(GF(prime), [_sage_const_0 , _sage_const_0 ]),
            ) + defect_vector
            right_side = (
                GF(prime)(q_values[_sage_const_0 ]) * ghost_zero_vector
                + GF(prime)(q_values[_sage_const_1 ]) * ghost_one_vector
            )
            assert left_side == right_side

            def wedge(left, right):
                return ZZ(
                    left[_sage_const_0 ] * right[_sage_const_1 ] - left[_sage_const_1 ] * right[_sage_const_0 ]
                )

            wedge_residuals = (
                ZZ(
                    GF(prime)(alpha[_sage_const_1 ])
                    * wedge(origin_vectors[_sage_const_0 ], origin_vectors[_sage_const_1 ])
                ),
                ZZ(
                    GF(prime)(alpha[_sage_const_2 ])
                    * wedge(origin_vectors[_sage_const_0 ], origin_vectors[_sage_const_2 ])
                ),
                wedge(origin_vectors[_sage_const_0 ], defect_vector),
                ZZ(
                    -GF(prime)(q_values[_sage_const_0 ])
                    * wedge(origin_vectors[_sage_const_0 ], ghost_zero_vector)
                ),
            )
            assert (
                sum(wedge_residuals)
                - GF(prime)(q_values[_sage_const_1 ]) * determinant
            ) % prime == _sage_const_0 
            ore_elimination_records.append(
                (
                    margin,
                    alpha,
                    q_values,
                    tuple(value % prime for value in wedge_residuals),
                )
            )

    q0 = rational_mod(ore_quotient[_sage_const_0 ](n=residue), prime)
    q1 = rational_mod(ore_quotient[_sage_const_1 ](n=residue), prime)
    record = {
        "n": index,
        "core": (D, N),
        "p": prime,
        "r": residue,
        "target": apery_mod(residue, prime) == _sage_const_0 ,
        "b_next": apery_mod(residue + _sage_const_1 , prime),
        "ore_q": (q0, q1),
        "records": tuple(records),
        "ore_elimination": tuple(ore_elimination_records),
        "all_ghost_rank_two": tuple(all_ghost_records),
    }
    if "--profiles" in sys.argv:
        record["support_mod_p"] = {
            "origin": tuple(
                node - (prime - _sage_const_1 )
                for node in nodes
                if origin[node] % prime
            ),
            "ghost_one": tuple(
                node - (prime - _sage_const_1 )
                for node in nodes
                if ghost_one[node] % prime
            ),
        }
    return record


def audit_block(index, D, N):
    candidates = tuple(
        prime
        for prime in prime_range(D + _sage_const_1 , D + N + _sage_const_1 )
        if index - prime + _sage_const_9  <= prime - _sage_const_5 
    )
    if not candidates:
        return ()
    modulus = prod(prime**_sage_const_2  for prime in candidates)
    node_functions = build_node_functions(index, D, N, modulus)
    return tuple(
        audit_candidate(index, D, N, prime, node_functions)
        for prime in candidates
    )


