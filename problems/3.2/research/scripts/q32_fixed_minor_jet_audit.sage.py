def random_cases(count, seed, maximum_index):
    generator = random.Random(seed)
    cases = []
    while len(cases) < count:
        index = generator.randrange(_sage_const_80 , maximum_index + _sage_const_1 )
        N = generator.randrange(max(_sage_const_8 , index // _sage_const_12 ), max(_sage_const_9 , index // _sage_const_4 ))
        lower_D = (index - _sage_const_1 ) // _sage_const_2  + _sage_const_3 
        upper_D = index - N - _sage_const_2 
        if lower_D > upper_D:
            continue
        D = generator.randrange(lower_D, upper_D + _sage_const_1 )
        maximum_margin, _ = margin_data(index, D, N)
        if maximum_margin < _sage_const_2 :
            continue
        candidates = tuple(
            prime
            for prime in prime_range(D + _sage_const_1 , D + N + _sage_const_1 )
            if index - prime + _sage_const_9  <= prime - _sage_const_5 
        )
        if not candidates:
            continue
        prime = generator.choice(candidates)
        cases.append((index, D, N, prime))
    return tuple(cases)


